-- Money: DECIMAL(19,2) = exact decimal, 2 fraction digits (cents). Never FLOAT/DOUBLE.
-- Tax rates: DECIMAL(9,6), e.g. 0.070000 for 7 %.

-- ---------------------------------------------------------------------------
-- Transactions (one table for every type: flight, hotel, rail, navan_fee)
-- ---------------------------------------------------------------------------
CREATE TABLE transactions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id  VARCHAR(200)   NOT NULL,
    type         VARCHAR(20)    NOT NULL,
    currency     CHAR(3)        NOT NULL,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    total        DECIMAL(19, 2) NOT NULL,
    -- Type-specific details (coupons, hotel address, rail legs, fee_kind).
    -- Validated against a typed Java model per type before it is written.
    metadata     CLOB           NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_transactions_external_id UNIQUE (external_id),
    CONSTRAINT ck_transactions_type CHECK (type IN ('flight', 'hotel', 'rail', 'navan_fee'))
);

-- Government taxes (VAT, airport tax). Separate table from fees on purpose.
CREATE TABLE transaction_tax_lines (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT         NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    position       INT            NOT NULL,
    name           VARCHAR(200)   NOT NULL,
    rate           DECIMAL(9, 6),
    amount         DECIMAL(19, 2) NOT NULL,
    CONSTRAINT uq_tax_line_position UNIQUE (transaction_id, position)
);

-- Carrier / merchant fees (YQ surcharge, booking fee).
CREATE TABLE transaction_fee_lines (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT         NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    position       INT            NOT NULL,
    name           VARCHAR(200)   NOT NULL,
    amount         DECIMAL(19, 2) NOT NULL,
    CONSTRAINT uq_fee_line_position UNIQUE (transaction_id, position)
);

-- ---------------------------------------------------------------------------
-- Invoices: header + frozen copies (snapshots) of the billed transactions
-- ---------------------------------------------------------------------------
CREATE TABLE invoices (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency    CHAR(3)        NOT NULL,
    total       DECIMAL(19, 2) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- One row per billed transaction: a COPY of its data at invoice time.
-- transaction_id is UNIQUE: a transaction can be billed on at most one invoice
-- (prevents double billing; also gives a cheap "is this transaction invoiced?" lookup).
-- ON DELETE RESTRICT: the database itself refuses to delete a billed transaction.
CREATE TABLE invoice_lines (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id     BIGINT         NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    position       INT            NOT NULL,
    transaction_id BIGINT         NOT NULL REFERENCES transactions (id) ON DELETE RESTRICT,
    external_id    VARCHAR(200)   NOT NULL,
    type           VARCHAR(20)    NOT NULL,
    currency       CHAR(3)        NOT NULL,
    occurred_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    total          DECIMAL(19, 2) NOT NULL,
    metadata       CLOB           NOT NULL,
    CONSTRAINT uq_invoice_lines_transaction UNIQUE (transaction_id),
    CONSTRAINT uq_invoice_line_position UNIQUE (invoice_id, position)
);

CREATE TABLE invoice_line_tax_lines (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_line_id BIGINT         NOT NULL REFERENCES invoice_lines (id) ON DELETE CASCADE,
    position        INT            NOT NULL,
    name            VARCHAR(200)   NOT NULL,
    rate            DECIMAL(9, 6),
    amount          DECIMAL(19, 2) NOT NULL
);

CREATE TABLE invoice_line_fee_lines (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_line_id BIGINT         NOT NULL REFERENCES invoice_lines (id) ON DELETE CASCADE,
    position        INT            NOT NULL,
    name            VARCHAR(200)   NOT NULL,
    amount          DECIMAL(19, 2) NOT NULL
);

-- ---------------------------------------------------------------------------
-- Indexes. Primary keys and UNIQUE constraints are backed by indexes automatically:
--   transactions.id, invoices.id                -> GET by id
--   transactions.external_id                    -> duplicate detection
--   invoice_lines.transaction_id                -> "is this transaction on an invoice?"
--   (transaction_id, position) on tax/fee lines -> load a transaction's lines
--   (invoice_id, position) on invoice_lines     -> load an invoice's lines
-- Remaining foreign keys used for child lookups:
-- ---------------------------------------------------------------------------
CREATE INDEX ix_inv_line_tax_lines_line    ON invoice_line_tax_lines (invoice_line_id);
CREATE INDEX ix_inv_line_fee_lines_line    ON invoice_line_fee_lines (invoice_line_id);
